"""Process and storage boundaries used by desktop lifecycle coordination."""

from typing import Protocol


class JobProcessPort(Protocol):
    def drain(self, manager, events): ...
    def launch(self, manager, operation, payload, job_id, reconciliation_admitted, helper_nonce, approved_analysis_plan, request): ...
    def join_descendants(self, manager, pid): ...
    def stop(self, manager): ...


class JobStoragePort(Protocol):
    def check_regular_path(self, path): ...
    def recover(self, paths): ...
    def validate_payload(self, payload): ...
    def _walk_forward_owner_path(self, paths, reference): ...
    def _claim_walk_forward(self, paths, reference, job_id): ...
    def _check_walk_forward_owner(self, paths, job_id, reference): ...
    def worker_paths(self, root, bootstrap): ...
    def configure_workspace(self, paths, destination): ...


class JobEventLogPort(Protocol):
    def append(self, operation, event_type, *, error_code=None): ...
    def tail(self, limit=200): ...
