"""Descriptors for shared page data and explicit host callback bindings."""


class StateField:
    def __set_name__(self, owner, name):
        self.name = name

    def __get__(self, instance, owner=None):
        if instance is None:
            return self
        return getattr(instance.page_state, self.name)

    def __set__(self, instance, value):
        setattr(instance.page_state, self.name, value)

    def __delete__(self, instance):
        # unittest.mock.patch.object restores via delattr when the attribute was not instance-owned.
        delattr(instance.page_state, self.name)


class HostMethod:
    def __init__(self, name):
        self.name = name

    def __get__(self, instance, owner=None):
        if instance is None:
            return self
        callback = getattr(instance.host, self.name, None)
        return callback if callback is not None else instance.host.callbacks[self.name]


